public class Loops {
    public static void main(String[] args) {

        // For Loop



        for (int counter = 0; counter < 10; counter++) {
            System.out.println("Hello World..!");
        }


        // While Loop


        int i= 1;
        while (i<10) {
            System.out.println(i);
            i++;
        }


        // Do While loop
        
        int j=11;
        do{
            System.out.println(j+" ");
            j++;
        }while(j<=20);

    }
}
